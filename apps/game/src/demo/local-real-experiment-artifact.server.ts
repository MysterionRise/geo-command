import "server-only";

import {
  LANGUAGE_CANDIDATES,
  PROVENANCE_CANDIDATES,
  PROVENANCE_CANDIDATE_LABELS,
  PROVENANCE_CLUES,
  PROVENANCE_COUNT,
  PROVENANCE_PROMPT,
  ROUND_COUNT,
  STACK_REVISION,
  fail,
  type JsonRecord,
  type ParsedFixture,
  type ParsedSource,
} from "./local-real-experiment-domain.server";
import {
  validateLanguageSource,
  validateProvenanceSource,
} from "./local-real-experiment-source.server";
import {
  canonicalHash,
  codeText,
  containsProtected,
  deepFreeze,
  positiveInteger,
  rawHash,
  record,
  serializeCanonical,
  sha256,
  text,
  texts,
} from "./local-real-experiment-validation.server";

const parseCandidates = (
  value: unknown,
  expected: readonly string[],
): readonly Readonly<{ id: string; label: string }>[] => {
  if (!Array.isArray(value) || value.length !== expected.length) return fail();
  const candidates = value.map((entry) => {
    const candidate = record(entry, ["id", "label"]);
    return Object.freeze({ id: text(candidate.id), label: text(candidate.label) });
  });
  if (candidates.map(({ id }) => id).join("|") !== expected.join("|")) fail();
  return Object.freeze(candidates);
};

const parseFixtureSource = (
  fixture: JsonRecord,
  index: number,
  snapshotId: string,
  profileVersion: string,
  queryIds: ReadonlySet<string>,
): ParsedSource => index < PROVENANCE_COUNT
  ? validateProvenanceSource(fixture.source, snapshotId, profileVersion, queryIds)
  : validateLanguageSource(
    fixture.source,
    snapshotId,
    profileVersion,
    index === PROVENANCE_COUNT ? "Python" : "TypeScript",
  );

const validateFixtureSemantics = (
  kind: "PROVENANCE" | "LANGUAGE",
  prompt: string,
  candidates: readonly Readonly<{ id: string; label: string }>[],
  clues: readonly string[],
  correctCandidateId: string,
  source: ParsedSource,
): void => {
  if (kind === "LANGUAGE") {
    const expectedCorrect = source.configuration === "Python"
      ? LANGUAGE_CANDIDATES[0]
      : LANGUAGE_CANDIDATES[1];
    if (correctCandidateId !== expectedCorrect) fail();
    return;
  }
  if (candidates.some(({ label }, index) => label !== PROVENANCE_CANDIDATE_LABELS[index])) fail();
  if (prompt !== PROVENANCE_PROMPT
    || clues.some((clue, index) => clue !== PROVENANCE_CLUES[index])) fail();
  const claimText = [prompt, ...candidates.map(({ label }) => label), ...clues].join("\n");
  if (/authored by|written by|generated by|human-only|ai detector|code style (?:shows|proves|indicates)/iu.test(claimText)) fail();
  const expectedCorrect = source.markerMatched
    ? PROVENANCE_CANDIDATES[0]
    : PROVENANCE_CANDIDATES[1];
  if (correctCandidateId !== expectedCorrect) fail();
};

const parseAttribution = (value: unknown, source: ParsedSource): string => {
  const attribution = text(value);
  for (const required of [
    source.authorName, source.repository, source.licenseName, source.licenseSpdx, source.blobUrl,
  ]) {
    if (!attribution.includes(required)) fail();
  }
  return attribution;
};

const parseFixture = (
  value: unknown,
  index: number,
  snapshotId: string,
  profileVersion: string,
  queryIds: ReadonlySet<string>,
): ParsedFixture => {
  const fixture = record(value, [
    "kind", "roundId", "roundVersion", "excerpt", "prompt", "candidates", "clues",
    "correctCandidateId", "evidence", "explanation", "attribution", "helpfulSignals",
    "misleadingSignals", "source",
  ]);
  const kind = index < PROVENANCE_COUNT ? "PROVENANCE" : "LANGUAGE";
  if (fixture.kind !== kind) fail();
  const excerpt = codeText(fixture.excerpt);
  const prompt = text(fixture.prompt);
  const expectedCandidates = kind === "PROVENANCE" ? PROVENANCE_CANDIDATES : LANGUAGE_CANDIDATES;
  const candidates = parseCandidates(fixture.candidates, expectedCandidates);
  const clues = texts(fixture.clues, 2);
  const correctCandidateId = text(fixture.correctCandidateId);
  if (!expectedCandidates.includes(correctCandidateId as never)) fail();
  const source = parseFixtureSource(fixture, index, snapshotId, profileVersion, queryIds);
  if (source.excerptHash !== rawHash(excerpt)) fail();
  validateFixtureSemantics(kind, prompt, candidates, clues, correctCandidateId, source);
  return deepFreeze({
    kind,
    roundId: text(fixture.roundId),
    roundVersion: sha256(fixture.roundVersion),
    excerpt,
    prompt,
    candidates,
    clues,
    correctCandidateId,
    evidence: text(fixture.evidence),
    explanation: text(fixture.explanation),
    attribution: parseAttribution(fixture.attribution, source),
    helpfulSignals: texts(fixture.helpfulSignals),
    misleadingSignals: texts(fixture.misleadingSignals),
    source,
  });
};

const requirePublicContainment = (fixtures: readonly ParsedFixture[]): void => {
  const protectedSourceKeys = [
    "repository", "repositoryUrl", "authorName", "authorLogin", "authorSourceUrl", "path",
    "blob", "rawContentHash", "licenseName", "licenseSpdx", "licenseFileUrl", "commit",
    "commitUrl", "blobUrl",
  ] as const;
  const publicText = serializeCanonical(fixtures.map((fixture) => ({
    excerpt: fixture.excerpt,
    prompt: fixture.prompt,
    candidates: fixture.candidates,
    clues: fixture.clues,
  })));
  for (const fixture of fixtures) {
    const protectedValues = [
      fixture.evidence,
      fixture.explanation,
      fixture.attribution,
      ...protectedSourceKeys.map((key) => fixture.source[key]),
    ];
    if (protectedValues.some((value) =>
      typeof value === "string" && containsProtected(publicText, value))) fail();
  }
};

const parseSnapshot = (value: unknown, profileHash: string): Readonly<{
  id: string;
  profileVersion: string;
  queryIds: ReadonlySet<string>;
}> => {
  const snapshot = record(value, [
    "id", "profileVersion", "profileHash", "github", "stack", "acceptedResponseHashes",
  ]);
  const id = sha256(snapshot.id);
  const profileVersion = text(snapshot.profileVersion);
  if (sha256(snapshot.profileHash) !== profileHash) fail();
  const github = record(snapshot.github, ["apiVersion", "queries"]);
  text(github.apiVersion);
  const queries = Array.isArray(github.queries) ? github.queries : fail();
  if (queries.length === 0) fail();
  const queryIds = new Set<string>(queries.map((entry: unknown) => {
    const query = record(entry, ["id", "query", "sort", "order", "pages", "resultCeiling"]);
    if (query.sort !== "committer-date" || query.order !== "desc") fail();
    text(query.query);
    positiveInteger(query.pages);
    positiveInteger(query.resultCeiling);
    return text(query.id);
  }));
  if (queryIds.size !== queries.length) fail();
  validateSnapshotStack(snapshot.stack);
  validateResponseHashes(snapshot.acceptedResponseHashes, id, profileHash);
  return Object.freeze({ id, profileVersion, queryIds });
};

const validateSnapshotStack = (value: unknown): void => {
  const stack = record(value, ["release", "revision", "configurations"]);
  if (stack.release !== "v2.2.0" || stack.revision !== STACK_REVISION
    || !Array.isArray(stack.configurations)
    || stack.configurations.length !== 2
    || stack.configurations[0] !== "Python"
    || stack.configurations[1] !== "TypeScript") fail();
};

const validateResponseHashes = (
  value: unknown,
  snapshotId: string,
  profileHash: string,
): void => {
  const acceptedResponseHashes = Array.isArray(value) ? value : fail();
  if (acceptedResponseHashes.length === 0) fail();
  const responseHashes = acceptedResponseHashes.map(sha256);
  if (new Set(responseHashes).size !== responseHashes.length
    || snapshotId !== canonicalHash({ profileHash, acceptedResponseHashes: responseHashes })) fail();
};

const validateFixtureSet = (fixtures: readonly ParsedFixture[]): void => {
  const roundIds = fixtures.map(({ roundId }) => roundId.toLocaleLowerCase("en-US"));
  if (new Set(roundIds).size !== fixtures.length) fail();
  const markerResults = fixtures.slice(0, PROVENANCE_COUNT)
    .map(({ source }) => source.markerMatched);
  if (!markerResults.includes(true) || !markerResults.includes(false)) fail();
  for (const key of [
    "repository", "commit", "path", "blob", "rawContentHash", "excerptHash",
  ] as const) {
    const identities = fixtures.map(({ source }) => source[key]);
    if (new Set(identities).size !== fixtures.length) fail();
  }
  requirePublicContainment(fixtures);
};

export const parseArtifact = (value: unknown): readonly ParsedFixture[] => {
  const artifact = record(value, [
    "schemaVersion", "contentClass", "profileHash", "crawlSnapshot", "fixtures",
  ]);
  if (artifact.schemaVersion !== "local-experiment-artifact.v1"
    || artifact.contentClass !== "LOCAL_UNREVIEWED_EXPERIMENT") fail();
  const profileHash = sha256(artifact.profileHash);
  const snapshot = parseSnapshot(artifact.crawlSnapshot, profileHash);
  const artifactFixtures = Array.isArray(artifact.fixtures) ? artifact.fixtures : fail();
  if (artifactFixtures.length !== ROUND_COUNT) fail();
  const fixtures = artifactFixtures.map((fixture: unknown, index: number) =>
    parseFixture(fixture, index, snapshot.id, snapshot.profileVersion, snapshot.queryIds));
  validateFixtureSet(fixtures);
  return Object.freeze(fixtures);
};
